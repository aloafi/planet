export function t(key: Key, vars?: Record<string, string | number>) {
  let s = (current === 'ar' ? ar : en)[key] ?? en[key] ?? key
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]))
  return s
}
