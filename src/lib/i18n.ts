/**
 * One language for the whole site — English or Arabic (right-to-left).
 * The AI follows the same setting.
 */
export type Lang = 'en' | 'ar'

let current: Lang = 'en'
export const setLang = (l: Lang) => {
  current = l === 'ar' ? 'ar' : 'en'
}
export const getLang = () => current
export const isAr = () => current === 'ar'

/** Gregorian calendar and Latin digits in both languages */
export const locale = () => (current === 'ar' ? 'ar-u-ca-gregory-nu-latn' : 'en-US')
export const fmtDate = (d: Date | number, o: Intl.DateTimeFormatOptions) => new Date(d).toLocaleDateString(locale(), o)

/** Arabic counting: 1 = singular, 2 = dual, 3–10 = plural, 11+ = singular accusative */
function arCount(n: number, one: string, two: string, few: string, many: string) {
  if (n === 1) return one
  if (n === 2) return two
  if (n >= 3 && n <= 10) return `${n} ${few}`
  return `${n} ${many}`
}

export const nTasks = (n: number) => (isAr() ? arCount(n, 'مهمة واحدة', 'مهمتان', 'مهام', 'مهمة') : `${n} ${n === 1 ? 'task' : 'tasks'}`)
export const nBreaks = (n: number) => (isAr() ? arCount(n, 'استراحة واحدة', 'استراحتان', 'استراحات', 'استراحة') : `${n} ${n === 1 ? 'break' : 'breaks'}`)
export const nDays = (n: number) => (isAr() ? arCount(n, 'يوم', 'يومين', 'أيام', 'يوماً') : `${n} ${n === 1 ? 'day' : 'days'}`)
/** "45 min" / "45 دقيقة" (number always shown) */
export const nMin = (n: number) => {
  if (!isAr()) return `${n} min`
  if (n === 1) return '1 دقيقة'
  if (n === 2) return '2 دقيقتان'
  if (n >= 3 && n <= 10) return `${n} دقائق`
  return `${n} دقيقة`
}

